// Rebuild the vendored provider library after updating the pinned dependencies.
import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const driveRoot = realpathSync(resolve(here, 'node_modules/@usync/drive'));
const oauthRoot = realpathSync(resolve(here, 'node_modules/@usync/oauth2'));
const licenses = [
  ['@usync/drive', resolve(driveRoot, 'LICENSE')],
  ['@usync/oauth2', resolve(oauthRoot, 'LICENSE')],
  ['@usync/util', resolve(driveRoot, '../util/LICENSE')],
  ['nanoid', resolve(oauthRoot, '../../nanoid/LICENSE')],
].map(([name, file]) => {
  let text; try { text = readFileSync(file, 'utf8'); } catch (e) { if (name !== '@usync/util') throw e; text = readFileSync(resolve(here, 'node_modules/@usync/drive/LICENSE'), 'utf8'); }
  return '/*! ' + name + '\n' + text.replace(/\r\n/g, '\n').replace(/\*\//g, '* /') + ' */';
}).join('\n');
const result = buildSync({
  stdin: { contents: 'export * from "@usync/drive"; export * from "@usync/oauth2";', resolveDir: here },
  bundle: true, write: false, minify: true, format: 'iife', globalName: '__stProviders', platform: 'browser', target: 'es2020', legalComments: 'inline',
});
writeFileSync(resolve(here, 'providers.js'), '// Generated by build-providers.mjs; do not edit. Pinned versions: package.json.\n' + licenses
  + '\nvar stSyncProviders = (function (fetch) {\n' + result.outputFiles[0].text + '\nreturn __stProviders;\n})(stSyncFetch);\n');
console.log('Providers: ' + result.outputFiles[0].contents.length + ' bytes minified (plus licenses)');
